#!/usr/bin/env bash

readonly AWGPROXY_DIR="/etc/awgproxy"
readonly AWGPROXY_CONFIG="$AWGPROXY_DIR/awgproxy.conf"
readonly AWG_CONFIG_DIR="/etc/amnezia/amneziawg"
readonly AWG_CONFIG="$AWG_CONFIG_DIR/awg0.conf"
readonly BACKUP_DIR="/var/backups/awgproxy"
readonly STATE_DIR="/var/lib/awgproxy"
readonly LOG_TAG="awgproxy"

if [[ -t 1 ]]; then
  C_RESET=$'\033[0m'; C_RED=$'\033[31m'; C_GREEN=$'\033[32m'; C_YELLOW=$'\033[33m'; C_CYAN=$'\033[36m'
else
  C_RESET=''; C_RED=''; C_GREEN=''; C_YELLOW=''; C_CYAN=''
fi

info() { printf '%s[INFO]%s %s\n' "$C_CYAN" "$C_RESET" "$*"; }
ok() { printf '%s[PASS]%s %s\n' "$C_GREEN" "$C_RESET" "$*"; }
warn() { printf '%s[WARN]%s %s\n' "$C_YELLOW" "$C_RESET" "$*" >&2; }
die() { printf '%s[FAIL]%s %s\n' "$C_RED" "$C_RESET" "$*" >&2; exit 1; }
require_root() { [[ ${EUID:-$(id -u)} -eq 0 ]] || die "this command requires root"; }
have() { command -v "$1" >/dev/null 2>&1; }
confirm() {
  local prompt=${1:-Continue?} default=${2:-n} hint='y/N' answer
  if [[ $default == y ]]; then hint='Y/n'; fi
  read -r -p "$prompt [$hint] " answer || return 1
  answer=${answer:-$default}
  [[ $answer == [yY] || $answer == [yY][eE][sS] || $answer == [дД] || $answer == [дД][аА] ]]
}
prompt_default() {
  local prompt=$1 default=$2 value
  read -r -p "$prompt [$default]: " value || return 1
  printf '%s' "${value:-$default}"
}
is_ipv4() {
  local ip=$1 IFS=. octets=()
  read -r -a octets <<< "$ip"
  [[ ${#octets[@]} -eq 4 ]] || return 1
  local octet
  for octet in "${octets[@]}"; do [[ $octet =~ ^[0-9]+$ && 10#$octet -le 255 ]] || return 1; done
}
is_cidr() {
  local value=$1 ip prefix
  ip=${value%/*}; prefix=${value#*/}
  [[ $value == */* ]] && is_ipv4 "$ip" && [[ $prefix =~ ^[0-9]+$ ]] && (( prefix <= 32 ))
}
validate_cidr_list() {
  local item list=${1// /}
  IFS=',' read -r -a items <<< "$list"
  ((${#items[@]} > 0)) || return 1
  for item in "${items[@]}"; do is_cidr "$item" || return 1; done
}
atomic_install() {
  local source=$1 target=$2 mode=${3:-0644} target_dir tmp
  target_dir=$(dirname -- "$target")
  install -d -m 0755 "$target_dir"
  tmp=$(mktemp "$target_dir/.awgproxy.XXXXXX")
  install -m "$mode" "$source" "$tmp"
  mv -f -- "$tmp" "$target"
}
current_lan_ipv4() {
  ip -o -4 addr show dev "$1" scope global primary 2>/dev/null |
    awk '{ split($4, address, "/"); ip = address[1] } END { if (NR != 1) exit 1; print ip }'
}

load_config() {
  [[ -r $AWGPROXY_CONFIG ]] || die "AWG Proxy is not configured; run: awgproxy install"
  # This file is generated by AWG Proxy and contains shell-escaped values.
  # shellcheck disable=SC1090
  source "$AWGPROXY_CONFIG"
  LAN_ADDRESS_MODE=${LAN_ADDRESS_MODE:-static}
  if [[ $LAN_ADDRESS_MODE == auto && ${1:-} != saved ]]; then
    LAN_IP=$(current_lan_ipv4 "$LAN_IF") ||
      die "cannot determine a unique primary IPv4 on $LAN_IF"
  fi
}
csv_to_nft() { local value=${1//,/", "}; printf '%s' "$value"; }
service_active() { systemctl is-active --quiet "$1"; }
pause() { [[ -t 0 ]] && read -r -p "Press Enter to continue..." _ || true; }
